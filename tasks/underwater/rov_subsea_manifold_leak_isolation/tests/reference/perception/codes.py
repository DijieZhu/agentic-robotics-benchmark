"""Square plate codes: dictionary and the fixed, unprivileged decoder (numpy + scipy only).

Code = 8 x 8 cells: a one-cell black border around 6 x 6 data cells (panel_std: 20 mm cells, 160 mm outer square), on a
white quiet zone >= 1 cell wide.  Bit 1 = black.  Bit index = 6 * row + col of the data grid, row 0 at the top, col 0
at the left, with the plate upright.

Dictionary: our own, generated by a seeded greedy search (`generate_dictionary`), stored in panel_codes.json next to
this file.  Rotation-robust: every codeword and each of its 90/180/270 deg rotations differ from every other codeword in
any rotation, and from its own other rotations, in >= dmin bits (dmin = 12 for the 48-word table).

Decoder (`decode`): multi-scale adaptive threshold -> dark 8-connected components -> convex hull reduced to a quad ->
sub-pixel edge refinement -> homography -> 3 x 3 samples per cell in the inner 40 % of each cell -> black level from the
28 border cells, white level from the 36 quiet-zone cells just outside the marker (each a plane fit over the marker)
-> border / quiet-zone validity -> hard bits -> nearest codeword over the 4 rotations, accepted if <= max_errors bits
differ -> de-duplication.  Interface used by the pilots:

    decode(frame_rgb) -> [(code_id, corners_px)]      corners_px (4, 2): the code's own TL, TR, BR, BL
"""
from __future__ import annotations

import json
import math
import os
from functools import lru_cache
from typing import Optional

import numpy as np

from . import imgproc as IP  # P14: package-relative import (G4: sys.path insert + top-level import)
from . import panel_std as PS

HERE = os.path.dirname(os.path.abspath(__file__))
DICT_PATH = os.path.join(HERE, "panel_codes.json")
N = PS.DATA_N
M = PS.MARKER_N


# ================================================================================================ dictionary
def _rot_perms():
    idx = np.arange(N * N).reshape(N, N)
    return [np.rot90(idx, k).reshape(-1) for k in range(4)]


def generate_dictionary(n_words: int = 48, dmin: int = 12, seed: int = 20261114, pop=(12, 24),
                        max_candidates: int = 400000) -> dict:
    perms = _rot_perms()
    rng = np.random.default_rng(seed)
    words, allrot = [], np.zeros((0, N * N), np.uint8)
    tried = 0
    while len(words) < n_words and tried < max_candidates:
        tried += 1
        w = rng.integers(0, 2, N * N).astype(np.uint8)
        if not (pop[0] <= int(w.sum()) <= pop[1]):
            continue
        R = np.stack([w[p] for p in perms])
        if min(int((R[0] != R[k]).sum()) for k in (1, 2, 3)) < dmin:
            continue
        if len(allrot) and int((R[:, None, :] != allrot[None]).sum(-1).min()) < dmin:
            continue
        words.append(w)
        allrot = np.concatenate([allrot, R])
    if len(words) < n_words:
        raise RuntimeError(f"only {len(words)} words at dmin {dmin}")
    W = np.stack(words)
    st = dictionary_stats(W)
    return {"schema": "g4-panel-codes/1", "grid": [N, N], "border_cells": PS.BORDER, "cell_m": PS.CELL,
            "bit_order": "row-major from the top-left data cell of the upright code, 1 = black",
            "generator": {"seed": seed, "dmin_target": dmin, "popcount": list(pop), "candidates_tried": tried},
            "stats": st, "codes": [{"id": i, "bits": "".join(str(int(b)) for b in w)} for i, w in enumerate(W)]}


def dictionary_stats(W: np.ndarray) -> dict:
    perms = _rot_perms()
    R = np.stack([W[:, p] for p in perms], 1)                    # (n, 4, 36)
    n = len(W)
    flat = R.reshape(-1, N * N)
    D = (flat[:, None, :] != flat[None, :, :]).sum(-1)
    owner = np.repeat(np.arange(n), 4)
    same = owner[:, None] == owner[None, :]
    eye = np.eye(len(flat), dtype=bool)
    inter = D[~same].min()
    self_rot = D[same & ~eye].min()
    upright = (W[:, None, :] != W[None, :, :]).sum(-1)[~np.eye(n, dtype=bool)].min()
    return {"n_words": int(n), "min_distance_any_rotation": int(min(inter, self_rot)),
            "min_distance_between_words_all_rotations": int(inter), "min_distance_word_vs_own_rotations": int(self_rot),
            "min_distance_upright_only": int(upright)}


@lru_cache(maxsize=4)
def load_dictionary(path: str = DICT_PATH) -> np.ndarray:
    with open(path) as f:
        js = json.load(f)
    return np.array([[int(c) for c in e["bits"]] for e in js["codes"]], np.uint8)


def code_grid(code_id: int, dictionary: Optional[np.ndarray] = None) -> np.ndarray:
    """(8, 8) uint8, 1 = black, including the border."""
    W = load_dictionary() if dictionary is None else dictionary
    g = np.ones((M, M), np.uint8)
    g[1:-1, 1:-1] = W[code_id].reshape(N, N)
    return g


# ================================================================================================ decoder
_CANON = np.array([[0.0, 0.0], [M, 0.0], [M, M], [0.0, M]])       # marker TL, TR, BR, BL in cell units (x right, y down)
_SUB = np.array([-0.2, 0.0, 0.2])


def _plane_fit(rc: np.ndarray, val: np.ndarray):
    A = np.concatenate([np.ones((len(rc), 1)), rc], 1)
    ok = np.isfinite(val)
    if ok.sum() < 6:
        return None
    coef, *_ = np.linalg.lstsq(A[ok], val[ok], rcond=None)
    return coef


_RING = [(i, j) for i in range(-1, M + 1) for j in range(-1, M + 1) if i in (-1, M) or j in (-1, M)]
_BORD = [(i, j) for i in range(M) for j in range(M) if i in (0, M - 1) or j in (0, M - 1)]
_DATA = [(i, j) for i in range(1, M - 1) for j in range(1, M - 1)]


_ALLC = _RING + _BORD + _DATA
_ROWS = np.array([c[0] for c in _ALLC])
_COLS = np.array([c[1] for c in _ALLC])
_OY, _OX = np.meshgrid(_SUB, _SUB, indexing="ij")
_XS = (_COLS[:, None] + 0.5 + _OX.reshape(1, -1)).reshape(-1)
_YS = (_ROWS[:, None] + 0.5 + _OY.reshape(1, -1)).reshape(-1)
_NR, _NB = len(_RING), len(_BORD)
_RC_R = np.array(_RING, float)
_RC_B = np.array(_BORD, float)
_RC_D = np.array(_DATA, float)
_PRE = np.array(_RING + _BORD, float) + 0.5          # cell centres (row, col) for the quick check


def _precheck(gray, quad) -> bool:
    """Cheap test on the unrefined quad: one sample per border / quiet-zone cell."""
    Hm = IP.homography(_CANON, quad)
    uv = IP.apply_h(Hm, _PRE[:, ::-1])
    v = IP.bilinear(gray, uv[:, 0], uv[:, 1])
    if np.isnan(v).mean() > 0.05:
        return False
    ring, bord = v[:_NR], v[_NR:]
    thr = 0.5 * (np.nanmedian(ring) + np.nanmedian(bord))
    if np.nanmedian(ring) - np.nanmedian(bord) < 0.02:
        return False
    return (np.mean(bord < thr) >= 0.75) and (np.mean(ring > thr) >= 0.7)


def _read_quad(gray, quad, W, max_errors):
    Hm = IP.homography(_CANON, quad)
    uv = IP.apply_h(Hm, np.stack([_XS, _YS], 1))
    s = IP.bilinear(gray, uv[:, 0], uv[:, 1]).reshape(len(_ALLC), 9)
    if np.isnan(s).mean() > 0.02:
        return None
    v = np.nanmean(s, 1)
    ring, bord, data = v[:_NR], v[_NR:_NR + _NB], v[_NR + _NB:]
    cw = _plane_fit(_RC_R, ring)
    cb = _plane_fit(_RC_B, bord)
    if cw is None or cb is None:
        return None
    lvl = lambda coef, rc: coef[0] + rc @ coef[1:]
    white_R, black_B = lvl(cw, _RC_R), lvl(cb, _RC_B)
    contrast = float(np.median(white_R) - np.median(black_B))
    noise = float(1.4826 * np.median(np.abs(np.concatenate([ring - white_R, bord - black_B]))) + 1e-4)
    if contrast < 0.035 or contrast < 3.0 * noise:
        return None
    thr = lambda rc: 0.5 * (lvl(cw, rc) + lvl(cb, rc))
    if int((bord < thr(_RC_B)).sum()) < _NB - 2:
        return None
    if int((ring > thr(_RC_R)).sum()) < _NR - 4:
        return None
    bits = (data < thr(_RC_D)).astype(np.uint8).reshape(N, N)
    best = (99, -1, -1)
    for k in range(4):
        g = np.rot90(bits, -k).reshape(-1)
        dist = (W != g[None, :]).sum(1)
        i = int(np.argmin(dist))
        if dist[i] < best[0]:
            best = (int(dist[i]), i, k)
    if best[0] > max_errors:
        return None
    dist, cid, k = best
    corners = np.array([quad[(m - k) % 4] for m in range(4)])
    return {"code_id": cid, "corners": corners, "errors": dist, "rotation": k, "contrast": contrast, "noise": noise}


def decode_verbose(frame_rgb: np.ndarray, dictionary: Optional[np.ndarray] = None, max_errors: int = 2,
                   min_cell_px: float = 2.0) -> list[dict]:
    W = load_dictionary() if dictionary is None else dictionary
    gray = IP.to_gray(frame_rgb)
    Hh, Ww = gray.shape
    sc = Ww / 640.0
    wins = sorted({max(5, int(round(w * sc)) | 1) for w in (15, 31, 61)})
    min_side = int(math.ceil(M * min_cell_px))
    min_area = int(0.3 * 28 * min_cell_px ** 2)
    found: list[dict] = []
    tried: list[np.ndarray] = []
    for win in wins:
        for cthr in (0.02, 0.05):
            mask = IP.adaptive_mask(gray, win, cthr, dark=True)
            for sub, org, area in IP.component_boxes(mask, min_area, min_side):
                h, w = sub.shape
                if max(h, w) > 5.0 * min(h, w):
                    continue
                pts = IP.region_hull_points(sub, org)
                quad, ratio = IP.hull_to_quad(pts)
                if quad is None or ratio < 0.85:
                    continue
                quad = IP.order_quad(quad)
                sides = np.hypot(*(np.roll(quad, -1, 0) - quad).T)
                if sides.min() < min_side or sides.max() > 4.0 * sides.min():
                    continue
                fill = area / max(IP.polygon_area(quad), 1.0)
                if fill < 0.3:
                    continue
                cell_px = float(sides.mean() / M)
                if any(float(np.mean(np.hypot(*(quad - t).T))) < max(1.0, 0.4 * cell_px) for t in tried):
                    continue
                tried.append(quad)
                if any(float(np.hypot(*(quad.mean(0) - r["corners"].mean(0)))) < 1.5 * cell_px for r in found):
                    continue
                if not _precheck(gray, quad):
                    continue
                qr = IP.refine_quad(gray, quad, band_px=0.8 * cell_px, inside_dark=True)
                res = _read_quad(gray, qr, W, max_errors)
                if res is None and qr is not quad:
                    res = _read_quad(gray, quad, W, max_errors)
                if res is not None:
                    res["cell_px"] = cell_px
                    found.append(res)
    # de-duplicate: overlapping corners -> keep fewest errors, then highest contrast; flag conflicting ids
    out: list[dict] = []
    for r in sorted(found, key=lambda r: (r["errors"], -r["contrast"])):
        c = r["corners"].mean(0)
        size = np.hypot(*(r["corners"][0] - r["corners"][2]))
        dup = [o for o in out if np.hypot(*(c - o["corners"].mean(0))) < 0.3 * size]
        if dup:
            if any(o["code_id"] != r["code_id"] for o in dup):
                r2 = dict(r)
                r2["conflict"] = True       # two different ids at the same place (never expected)
                out.append(r2)
            continue
        out.append(r)
    return out


def decode(frame_rgb: np.ndarray, dictionary: Optional[np.ndarray] = None, max_errors: int = 2):
    # P14: default correction limit 3 -> 2 (DESIGN 2.4, G4 section 5.7)
    """[(code_id, corners_px)], corners_px = the code's own TL, TR, BR, BL in continuous pixel coordinates."""
    return [(r["code_id"], r["corners"]) for r in decode_verbose(frame_rgb, dictionary, max_errors)]


